import { BadRequestException } from '@nestjs/common';

/**
 * التطبيع الموحّد لأرقام الهواتف الأردنية — يُستخدم في كل مكان يُكتب فيه
 * رقم إلى قاعدة v2 (دخول، إنشاء مالك/سائق/موظف) حتى لا يتكرر المستخدم
 * بصيغتين مختلفتين لنفس الرقم.
 *
 * **الأردن فقط، والقرار هنا لا في التطبيق**: التطبيق قد يُعدَّل أو يُتجاوَز
 * بطلب مباشر إلى الـAPI، فالحارس الحقيقي هو هذه الدالة — وكل مسار دخول يمر
 * بها (Firebase، واتساب، دخول التطوير) قبل أن يصل حساباً. رقم من خارج
 * الأردن يُرفض حتى لو نجح تحققه لدى Firebase.
 *
 * الصيغ المقبولة كلها لنفس الرقم: 0791234567 و791234567 و00962791234567
 * و+962791234567 — تُخزَّن جميعاً `+962791234567`.
 */
export function normalizeJordanPhone(raw: string): string {
  const p = toJordanE164(raw?.trim() ?? '');
  if (!p) {
    throw new BadRequestException(
      'الخدمة داخل الأردن فقط — أدخل رقم هاتف أردني (مثال: 0791234567)',
    );
  }
  return p;
}

/** يرجع الصيغة الدولية أو null — بلا رمي، لمن يحتاج الفحص لا الرفض */
export function toJordanE164(raw: string): string | null {
  let p = raw.replace(/[\s\-()]/g, '');
  if (p.startsWith('00962')) p = '+962' + p.slice(5);
  else if (p.startsWith('962')) p = '+' + p;
  else if (p.startsWith('07')) p = '+962' + p.slice(1);
  else if (/^7\d{8}$/.test(p)) p = '+962' + p;
  // مفاتيح المحمول الأردنية: 77 و78 و79 (و70 لبعض الخطوط). ما عداها ليس
  // محمولاً أردنياً — ورقم أرضي أو أجنبي لا يستقبل رمز تحقق أصلاً.
  return /^\+9627[0789]\d{7}$/.test(p) ? p : null;
}

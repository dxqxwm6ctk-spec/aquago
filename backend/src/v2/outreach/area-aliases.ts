/**
 * ربط أسماء المناطق الواردة من المصادر العامة بمناطق المنصة المسجَّلة
 * (`District`).
 *
 * **الجدول صغير عمداً.** قاعدة المنصة اليوم تحمل خمس مناطق فقط (زهران،
 * وادي السير، تلاع العلي، طارق، الجبيهة) — وهي ما زرعته البذرة، لا خريطة
 * أمانة عمّان كاملة. أما المصادر فتذكر عشرات المناطق الحقيقية (المقابلين،
 * القويسمة، ناعور، أبو علندا، ماركا، الجويدة، خريبة السوق…) التي **لا وجود
 * لها في القاعدة**.
 *
 * أمام ذلك خياران: أن نخترع مناطق لتستقبل السجلات، أو أن نترك `areaId` فارغاً
 * ونحفظ الاسم كما ورد في `areaName`. اخترنا الثاني: اختراع منطقة إدارية
 * يفسد الجغرافيا التي يقوم عليها التوزيع لاحقاً، بينما اسمٌ نصّي أمين لا
 * يضرّ ويُربط لاحقاً بضغطة حين تُستورد حدود عمّان الحقيقية عبر
 * `npm run v2:geo:import`.
 *
 * ولذلك لا يُوسَّع هذا الجدول بالتخمين. لا يُضاف مرادف إلا إذا كان مدعوماً
 * بما تعرفه المنصة نفسها (بذرة الأحياء في `prisma/seed.v2.ts`) أو بمطابقة
 * حرفية. «اللويبدة» مثلاً لا تُربط بـ«زهران» هنا لأن لا شيء في المشروع يقول
 * ذلك — تبقى نصّاً حتى تأتي بيانات حدود تحسمها.
 */

/**
 * مفتاح المقارنة: يوحّد ما يختلف إملائياً لا معنوياً. النصّ الأصلي لا يُمسّ —
 * هذا للمطابقة وحدها، تماماً كتطبيع الأسماء في كشف التكرار.
 */
export function normalizeAreaKey(raw: string): string {
  return (
    raw
      .trim()
      .toLowerCase()
      .replace(/[أإآ]/g, 'ا')
      .replace(/ة/g, 'ه')
      .replace(/ى/g, 'ي')
      .replace(/[ًٌٍَُِّْ]/g, '')
      .replace(/^(لواء|منطقة|قرية|حي|ضاحية)\s+/, '')
      .replace(/\s+/g, ' ')
      .trim()
  );
}

/**
 * كل ما يمكن أن يكون اسم منطقة في نصّ واحد.
 *
 * المصادر تكتب المكان بصيغ مركّبة بلا قاعدة: «البلد/وادي السير» تضع المنطقة
 * أخيراً، و«المقابلين/عمان» تضعها أولاً والمدينةَ أخيراً، و«خريبة السوق و
 * جاوا» تجمع مكانين بحرف عطف. أخذُ الجزء الأخير وحده — وهو ما كنّا نفعل —
 * يصيب في الأولى ويخطئ في الثانية فيبحث عن منطقة اسمها «عمان».
 *
 * فنجرّب النصّ كله وكل جزء منه، والأقوى أولاً: النصّ الكامل قبل أجزائه، حتى
 * لا يُقتطع اسمٌ مركّب صحيح إلى نصفه.
 */
export function areaKeyCandidates(raw: string): string[] {
  const whole = normalizeAreaKey(raw);
  const parts = raw
    .split(/[/،,]| و /)
    .map((p) => normalizeAreaKey(p))
    .filter((p) => p && p !== whole);
  // «عمان» و«العاصمة» اسما المدينة لا المنطقة — وجودهما يضلّل المطابقة
  const CITY_WORDS = new Set(['عمان', 'عمّان', 'العاصمه', 'الاردن']);
  return [whole, ...parts].filter((p) => !CITY_WORDS.has(p));
}


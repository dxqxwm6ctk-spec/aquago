#!/bin/sh
set -e

# إقلاع الحاوية — بلا هجرات ولا بذور (تُنفَّذ في docker-migrate.sh كخطوة
# نشر منفصلة تسبق ترقية أي حاوية؛ انظر التعليق هناك). هذا الملف يفترض أن
# المخطط مُطبَّق سلفاً على القاعدة، ولا يحاول تطبيقه بنفسه.
#
# لماذا هذا الفصل ضروري مع حاويتَي API: خطوة هجرة داخل كل إقلاع حاوية
# تعني حاويتين تتسابقان على قفل الهجرة الاستشاري عند كل نشر (Prisma
# يتعامل معه بأمان، لكن بلا داعٍ)، وفشل هجرة كان يُسقط كل حاوية على حدة
# بدل خطوة نشر واحدة واضحة تمنع الترقية قبل أن تبدأ.
. ./docker-common.sh

require_database_url_v2
wait_for_database

# الدور يُقرأ ويُطبَّق داخل main.ts (ROLE=api|worker، المرحلة 1.1) — هذا
# الملف لا يحتاج معرفة الدور، فقط إقلاع نفس العملية بلا فرق بين الدورين.
# قيمة ROLE غير المعروفة توقف main.ts نفسها لا هذا السكربت.
exec node dist/src/main.js

#!/bin/sh
set -e

# خطوة الهجرة والبذور — منفصلة عن إقلاع الحاوية (المرحلة 2.1).
#
# **لماذا الفصل:** كانت الحاوية تُشغّل migrate deploy + seed عند كل إقلاع
# — أي عند كل حاوية API جديدة، وكل إعادة تشغيل، وكل تحديث تلقائي. مع
# حاويتَي API يعني هذا سباقاً على قفل الهجرة الاستشاري في كل نشر (غير
# ضارّ — Prisma يتعامل معه بشكل صحيح — لكن يُطيل إقلاع الخاسر بلا داعٍ)،
# وفشل هجرة يوقف كل الحاويات معاً بدل خطوة نشر واحدة واضحة السبب.
#
# **مرة واحدة لكل نشر فعلياً لا بالاسم فقط:** يُشغَّل هذا كـ
# `deploy.preDeployCommand` في railway.json — Railway يُنفّذه مرة واحدة
# قبل ترقية أي حاوية، لا فرصة لتشغيلَين متزامنين من حاويتَين مختلفتَين
# كما كان يحدث سابقاً حين كانت الهجرة جزءاً من إقلاع كل حاوية.
#
# لا تُستدعى من docker-entrypoint.sh إطلاقاً — الحاوية تُقلع بافتراض أن
# المخطط مُطبَّق سلفاً، لا أن تطبّقه بنفسها.
#
# **AquaGo: مخطّط واحد لا اثنان.** GasGO كان يحمل مخطّطَين متوازيَين
# (legacy + v2) ريثما يكتمل ترحيله، فكانت هذه الخطوة تُهاجر وتبذر
# الاثنين. AquaGo بدأ من v2 مباشرة بلا تاريخ يُرحَّل، فحُذف شقّ legacy
# من هنا: لا هجرات له ولا `dist/prisma/seed.js` أصلًا، واستدعاؤه كان
# سيوقف كل نشر عند ملفٍ غير موجود.
. ./docker-common.sh

require_database_url_v2
wait_for_database

# `migrate deploy` لا `db push`: الأخيرة كانت تُشغَّل بـ--accept-data-loss عند
# كل إقلاع، أي أن إعادة تسمية عمود في المخطط تُسقط العمود وبياناته على
# الإنتاج بلا سؤال ولا سجل ولا رجعة. `migrate deploy` تطبّق ملفات الهجرة
# المراجَعة فقط، ولا تشتقّ فروقاً ولا تحذف شيئاً من تلقاء نفسها.
#
# الفشل يوقف خطوة النشر (set -e): نشرٌ بمخطط نصف مهاجَر أسوأ من نشر فاشل
# واضح — الثاني يمنع الترقية، والأول يفسد البيانات بهدوء بعد أن تُخدَّم.
#
# القاعدتان بُنيتا بـ`db push` فلا سجلّ هجرات لهما، و0_init تصف مخططاً
# موجوداً أصلاً. Prisma يرفض هذه الحالة بـP3005 «المخطط ليس فارغاً» —
# وهو وحده الخطأ الذي يعني «قاعدة قائمة تنتظر التأسيس»، فنسجّل عندها
# 0_init بـ`migrate resolve --applied` (تسجيل في جدول الهجرات بلا تنفيذ
# أي DDL — لا يلمس البيانات) ثم نعيد المحاولة.
#
# الحكم من خرج `migrate deploy` نفسه لا من `migrate status`: الأخيرة لا
# تُصدر P3005 إطلاقاً، وقراءة نصّها كانت تُسقط الحالة صمتاً فيفشل الإقلاع.
#
# idempotent: بعد نجاح التأسيس يصير جدول الهجرات موجوداً، فلا يتكرر P3005
# وتمرّ الاستدعاءات التالية من أول محاولة. وأي خطأ آخر يُعاد كما هو.

# ثنائية Prisma المحلية لا `npx prisma`.
#
# `npx` يُنزّل الحزمة من الشبكة إن لم يجدها محلياً — أي أن خطوة الهجرة
# تصير معتمدةً على الإنترنت وقد تجلب إصداراً يخالف package-lock. الثنائية
# موجودة في الصورة (يُبقيها npm لأنها peer اختياري لـ@prisma/client)،
# وغيابها يجب أن يوقف النشر لا أن يُطلق تنزيلاً صامتاً.
prisma_cli() {
  if [ ! -x ./node_modules/.bin/prisma ]; then
    echo "❌ ثنائية prisma مفقودة — الصورة بُنيت ناقصة، أُوقف النشر."
    exit 1
  fi
  ./node_modules/.bin/prisma "$@"
}

# البذور بـnode على الملف المُجمَّع، لا بـ`npx ts-node` على المصدر.
#
# **السبب مقيس لا نظري:** `ts-node` و`typescript` تبعيتا تطوير، يزيلهما
# `npm prune --omit=dev` في الصورة النهائية. عندها كان `npx ts-node`
# **يُنزّل ts-node من الشبكة** أثناء الهجرة ثم ينهار لغياب typescript:
#   TypeError: Cannot read properties of undefined (reading 'fileExists')
# فتفشل خطوة الهجرة كاملةً — ومعها بذور v2 التي تُنشئ فهارس GIST
# المكانية، فيعمل محرّك التوزيع بمسح تسلسلي بدل الفهرس.
#
# الملفان مُجمَّعان أصلاً (`tsconfig.json` يشمل `prisma/*.ts`)، فالتشغيل
# بـnode بلا شبكة ولا تبعيات تطوير — تماماً كما يفعل استيراد الوكالات
# أدناه. الغياب يوقف النشر صراحةً بدل أن يتخطّى البذور بصمت.
run_seed() {
  label="$1"; script="$2"
  if [ ! -f "$script" ]; then
    echo "❌ بذرة $label مفقودة: $script — الصورة بُنيت ناقصة، أُوقف النشر."
    exit 1
  fi
  node "$script"
}

migrate_with_baseline() {
  label="$1"; schema_arg="$2"
  out=$(prisma_cli migrate deploy $schema_arg 2>&1); rc=$?
  printf '%s\n' "$out"
  [ "$rc" -eq 0 ] && return 0

  printf '%s' "$out" | grep -q "P3005" || return "$rc"

  echo "🧱 $label: قاعدة قائمة بلا سجلّ هجرات — تسجيل 0_init كمُطبَّقة (بلا DDL)."
  prisma_cli migrate resolve --applied 0_init $schema_arg || return 1
  prisma_cli migrate deploy $schema_arg
}

echo "🗄️  تطبيق هجرات منصة v2..."
if ! migrate_with_baseline v2 "--schema prisma/v2/schema.prisma"; then
  echo "❌ فشل تطبيق هجرات v2 — أُوقفت خطوة النشر قبل ترقية أي حاوية."
  echo "   راجع './node_modules/.bin/prisma migrate status --schema prisma/v2/schema.prisma'."
  exit 1
fi
run_seed v2 dist/prisma/seed.v2.js

# استيراد الوكالات المحتملة معطَّل في AquaGo — عمدًا لا سهوًا.
#
# ملفات `prisma/data/agency-leads/` موروثة من GasGO: وكالات **غاز**
# مرخَّصة من وزارة الطاقة والثروة المعدنية. استيرادها هنا يملأ جدول
# الوكالات المحتملة بمنشآت لا تبيع مياهًا، فتصير قائمةُ التواصل عملًا
# مهدورًا في أحسن الأحوال، ورسائلَ إلى الجمهور الخطأ في أسوئها.
#
# آلية الاستيراد نفسها سليمة وتبقى في الصورة (`import-leads.cli.js`)؛
# ما ينقص هو مصدرُ بياناتٍ لموزّعي المياه. حين يتوفّر، يُعاد سطر
# `import-leads` هنا بملفاته الجديدة — ووجود الملفات القديمة إلى جانبه
# لا يكفي مبرّرًا لتشغيله.

echo "✅ خطوة الهجرة اكتملت."
